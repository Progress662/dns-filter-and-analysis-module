# SECTION 3: Demonstrate filtering and querying
# ─────────────────────────────────────────────────────────────────────────────

def demonstrate_filtering(records: List[DNSRecord]) -> None:
    """
    Show how to filter and query parsed DNS records.

    This demonstrates the kinds of queries a Feature Extraction Engine
    would run on parsed records.

    Args:
        records: List of DNSRecord objects to filter.
    """
    print("\n" + "="*70)
    print("  RECORD FILTERING EXAMPLES")
    print("="*70)

    # ── Filter 1: Failed queries (NXDOMAIN, SERVFAIL, etc.) ───────────────────
    failed_queries = [r for r in records if r.is_failed_query()]
    print(f"\n🔴 Failed queries (NXDOMAIN/SERVFAIL/etc.): {len(failed_queries)}")
    for r in failed_queries:
        print(f"   {r}")

    # ── Filter 2: Queries from internal (private) IPs ─────────────────────────
    internal_queries = [r for r in records if r.is_private_client()]
    print(f"\n🏠 Queries from internal IPs: {len(internal_queries)}")

    # ── Filter 3: Queries by type ──────────────────────────────────────────────
    type_counts: dict = {}
    for record in records:
        type_counts[record.query_type] = type_counts.get(record.query_type, 0) + 1

    print(f"\n📊 Query type breakdown:")
    for qtype, count in sorted(type_counts.items(), key=lambda x: -x[1]):
        bar = "█" * count
        print(f"   {qtype:<8} : {count:>3}  {bar}")

    # ── Filter 4: Unique domains queried ──────────────────────────────────────
    unique_domains = {r.domain for r in records}
    print(f"\n🌐 Unique domains queried: {len(unique_domains)}")
    for domain in sorted(unique_domains):
        print(f"   • {domain}")

    # ── Filter 5: Unique client IPs ────────────────────────────────────────────
    unique_clients = {r.client_ip for r in records}
    print(f"\n💻 Unique client IPs: {len(unique_clients)}")
    for ip in sorted(unique_clients):
        client_records = [r for r in records if r.client_ip == ip]
        nxdomain_count = sum(1 for r in client_records if r.response_code == "NXDOMAIN")
        print(f"   {ip:<16} — {len(client_records)} queries, {nxdomain_count} NXDOMAIN")

    # ── Filter 6: Low TTL records (potentially suspicious) ────────────────────
    low_ttl_records = [r for r in records if r.ttl is not None and r.ttl < 10]
    print(f"\n⏱  Very low TTL records (TTL < 10s): {len(low_ttl_records)}")
    for r in low_ttl_records:
        print(f"   TTL={r.ttl}s | {r.client_ip} → {r.domain}")


