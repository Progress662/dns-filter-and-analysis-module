# SECTION 2: Display parsed records
# ─────────────────────────────────────────────────────────────────────────────

def display_parsed_records(records: List[DNSRecord]) -> None:
    """
    Print all parsed DNS records in a readable format.

    Shows how to iterate over parsed records and access individual fields.

    Args:
        records: List of DNSRecord objects.
    """
    print("\n" + "="*70)
    print("  PARSED DNS RECORDS")
    print("="*70)
    print(f"{'#':<4} {'Timestamp':<22} {'Client IP':<16} {'Domain':<35} {'Type':<6} {'Code':<10} {'Resolved IP':<18} {'TTL'}")
    print("-"*130)

    for idx, record in enumerate(records, start=1):
        # Access fields using dot notation (because DNSRecord is a dataclass)
        print(
            f"{idx:<4} "
            f"{record.timestamp.strftime('%Y-%m-%d %H:%M:%S'):<22} "
            f"{record.client_ip:<16} "
            f"{record.domain:<35} "
            f"{record.query_type:<6} "
            f"{record.response_code:<10} "
            f"{record.resolved_ip or 'N/A':<18} "
            f"{record.ttl if record.ttl is not None else 'N/A'}"
        )

    print("-"*130)
    print(f"Total: {len(records)} records")


