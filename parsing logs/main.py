def demonstrate_dict_conversion(records: List[DNSRecord]) -> None:
    """
    Show how to convert DNSRecord objects back to dictionaries.

    This is important because downstream systems (databases, JSON APIs,
    pandas DataFrames) often expect plain dictionaries, not dataclass objects.

    Args:
        records: List of DNSRecord objects.
    """
    print("\n" + "="*70)
    print("  CONVERTING TO DICT FORMAT")
    print("="*70)

    if not records:
        print("No records to show.")
        return

    # Take the first record as an example
    first_record = records[0]

    print(f"\n🔷 DNSRecord object (dataclass):")
    print(f"   {first_record}")

    print(f"\n🔷 Same record as Python dict (via .to_dict()):")
    record_dict = first_record.to_dict()

    import json
    print(json.dumps(record_dict, indent=4))

    print(f"\n🔷 All records as list of dicts:")
    all_dicts = [r.to_dict() for r in records]
    print(f"   Generated {len(all_dicts)} dicts. First entry keys: {list(all_dicts[0].keys())}")



