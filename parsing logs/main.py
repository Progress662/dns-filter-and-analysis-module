def demonstrate_parsing() -> List[DNSRecord]:
    """
    Demonstrate parsing the normalized CSV produced by the Bind Converter.

    Returns:
        List[DNSRecord]: All parsed DNS records.
    """

    print("\n" + "=" * 70)
    print("  DNS LOG PARSER — CYBERSECURITY THREAT DETECTION PROJECT")
    print("=" * 70)

    # Create parser
    parser = DNSLogParser(strict_mode=False)

    all_records: List[DNSRecord] = []

    print("\n📊 Parsing normalized CSV generated by Bind Converter...")

    try:
        csv_result = parser.parse_file("normalized_dns_dataset.csv")
        all_records.extend(csv_result.records)
        print(csv_result.summary())

    except FileNotFoundError as e:
        print(f"  ⚠ {e}")

    print(f"\n✅ Total records loaded into memory: {len(all_records)}")

    return all_records

